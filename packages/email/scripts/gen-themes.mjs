#!/usr/bin/env node
/* Generates src/themes.generated.ts from the brand files of @krizaka/tokens (src/brands/*.brand.json): one email theme
   per brand, with the colours as hex (email clients do not read hsl() reliably). `--check` fails when the committed file
   is not what the brands say — a colour changes in @krizaka/tokens, then this is re-run. */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const brandsDir = path.join(here, "../../tokens/src/brands");
const out = path.join(here, "../src/themes.generated.ts");

function hsl(value) {
  const m = /^hsl\(\s*([\d.]+)\s+([\d.]+)%\s+([\d.]+)%\s*\)$/.exec(value);
  if (!m) throw new Error(`not an opaque hsl() colour: ${value}`);
  const [h, s, l] = [Number(m[1]), Number(m[2]) / 100, Number(m[3]) / 100];
  const k = (n) => (n + h / 30) % 12;
  const a = s * Math.min(l, 1 - l);
  const f = (n) => l - a * Math.max(-1, Math.min(k(n) - 3, Math.min(9 - k(n), 1)));
  return `#${[f(0), f(8), f(4)].map((x) => Math.round(x * 255).toString(16).padStart(2, "0")).join("")}`;
}

const pair = (node) => {
  const value = node.$value;
  return { dark: hsl(value), light: hsl(node.$extensions?.["com.krizaka"]?.light ?? value) };
};

const themes = {};
for (const file of fs.readdirSync(brandsDir).filter((f) => f.endsWith(".brand.json")).sort()) {
  const id = file.replace(".brand.json", "");
  const brand = JSON.parse(fs.readFileSync(path.join(brandsDir, file), "utf8"));
  const accent = pair(brand.accent.$root);
  const text = brand.accent.text ? pair(brand.accent.text) : accent;
  const on = pair(brand["on-accent"]);
  themes[id] = {
    accent: { light: accent.light, dark: accent.dark },
    onAccent: { light: on.light, dark: on.dark },
    link: { light: text.light, dark: text.dark },
  };
}

const body = `/* Generated by scripts/gen-themes.mjs from @krizaka/tokens (src/brands/*.brand.json). Do not edit: change the brand, re-run \`pnpm --filter @krizaka/email gen\`. */
export interface BrandColours {
  /** The button and the rule: \`light\` on a light page, \`dark\` when the client is in dark mode. */
  accent: { light: string; dark: string };
  /** The text on the button. */
  onAccent: { light: string; dark: string };
  /** The colour of a link in the text. */
  link: { light: string; dark: string };
}

export const BRAND_COLOURS = ${JSON.stringify(themes, null, 2)} as const satisfies Record<string, BrandColours>;

export type BrandId = keyof typeof BRAND_COLOURS;
`;

if (process.argv.includes("--check")) {
  if (!fs.existsSync(out) || fs.readFileSync(out, "utf8") !== body) {
    console.error("src/themes.generated.ts is out of date with @krizaka/tokens: run `pnpm --filter @krizaka/email gen`.");
    process.exit(1);
  }
} else {
  fs.writeFileSync(out, body);
}
