import { BRAND_COLOURS, type BrandColours, type BrandId } from "./themes.generated";

export { BRAND_COLOURS, type BrandColours, type BrandId };

/**
 * Every brand an email can wear: Krizaka (the default) and one per product, generated from @krizaka/tokens.
 * `orochia`, `yasakia`, `yororis` and `kachizaka` are paused products (2026-10-25): still accepted, removed in the next major.
 */
export const BRAND_IDS = Object.keys(BRAND_COLOURS) as BrandId[];

/** The names of the brands, as written on the logo and in the signature (a name is not translated). */
export const BRAND_NAMES: Record<BrandId, string> = {
  akinaza: "Akinaza",
  // Deprecated: a paused product (2026-10-25); its theme stays until the next major.
  kachizaka: "Kachizaka",
  krizaka: "Krizaka",
  orazaka: "Orazaka",
  // Deprecated: a paused product (2026-10-25); its theme stays until the next major.
  orochia: "Orochia",
  // Deprecated: a paused product (2026-10-25); its theme stays until the next major.
  yasakia: "Yasakia",
  yomizaka: "Yomizaka",
  // Deprecated: a paused product (2026-10-25); its theme stays until the next major.
  yororis: "Yororis",
};

/** Where the marks live: Bunny Storage, `brand/<brand>/mark-<light|dark>-256.png` (generated by krizaka-ui's export-brand). */
export const BRAND_CDN = "https://krizaka-assets.b-cdn.net";

/** The neutrals of every email — a page, a card, text, a quiet rule — in the two schemes. The accent comes from the brand. */
export interface Neutrals {
  page: string;
  card: string;
  quote: string;
  text: string;
  muted: string;
  border: string;
}

export const NEUTRALS: { light: Neutrals; dark: Neutrals } = {
  light: { page: "#f3f4f8", card: "#ffffff", quote: "#f4f6fb", text: "#12141a", muted: "#566073", border: "#e2e5ee" },
  dark: { page: "#0a0c11", card: "#13161d", quote: "#1b1f29", text: "#eceef4", muted: "#a4abbb", border: "#292e3a" },
};

export interface EmailTheme {
  id: BrandId;
  name: string;
  colours: BrandColours;
  neutrals: typeof NEUTRALS;
  /** The mark for a light page (a dark mark) and for a dark page (a light mark), as hosted PNGs. */
  logo: { light: string; dark: string };
}

/** The theme of a brand. House of Brands: an email wears one brand only, and never names another product. */
export function getTheme(id: BrandId = "krizaka", cdn: string = BRAND_CDN): EmailTheme {
  const base = cdn.replace(/\/$/, "");
  return {
    id,
    name: BRAND_NAMES[id],
    colours: BRAND_COLOURS[id],
    neutrals: NEUTRALS,
    logo: { light: `${base}/brand/${id}/mark-light-256.png`, dark: `${base}/brand/${id}/mark-dark-256.png` },
  };
}
