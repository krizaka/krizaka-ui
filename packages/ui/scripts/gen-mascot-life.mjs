#!/usr/bin/env node
/* The flock's life as a stylesheet: src/mascots/life.ts holds the characters (data), this writes their CSS between the
   `mascot-life` markers of src/blocks.css — a block's styles are imported once by the app, not once per bird. A test
   (src/mascots/life.test.ts) keeps the two equal.   Usage: node scripts/gen-mascot-life.mjs [--check] */
import { readFileSync, writeFileSync } from "node:fs";

import { lifeCss } from "../src/mascots/life.ts";

const file = new URL("../src/blocks.css", import.meta.url);
const BEGIN = "/* mascot-life:begin — generated by scripts/gen-mascot-life.mjs from src/mascots/life.ts; do not edit */";
const END = "/* mascot-life:end */";
const section = `${BEGIN}\n${lifeCss()}\n${END}`;
const css = readFileSync(file, "utf8");
const a = css.indexOf(BEGIN);
const b = css.indexOf(END);
const next = a < 0 ? `${css.replace(/\n*$/, "\n")}\n/* Mascot life — the Flock's birds at ease, in character (Mascot \`life\`). */\n${section}\n` : `${css.slice(0, a)}${section}${css.slice(b + END.length)}`;
if (process.argv.includes("--check")) {
  if (next !== css) {
    console.error("src/blocks.css is out of date with src/mascots/life.ts: run `node scripts/gen-mascot-life.mjs`");
    process.exit(1);
  }
} else {
  writeFileSync(file, next);
  console.log("blocks.css: mascot-life section written");
}
