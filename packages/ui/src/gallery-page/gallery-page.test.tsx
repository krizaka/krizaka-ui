import { render, screen } from "@testing-library/react";

import Example from "../../registry/examples/gallery-page/made-here";
import { axeViolations } from "../test/axe";
import { GalleryPage } from "./index";

describe("GalleryPage", () => {
  it("renders the template with its h1, its parts, and no axe violation", async () => {
    const { container } = render(<Example />);
    expect(screen.getByRole("heading", { level: 1, name: "Generated by Orazaka itself" })).toBeTruthy();
    expect(container.querySelectorAll("figure.kz-tpl-figure")).toHaveLength(4);
    expect(screen.getByRole("img", { name: "Old harbour at dawn" })).toBeTruthy();
    expect(await axeViolations(container)).toEqual([]);
  });

  it("is exported", () => {
    expect(typeof GalleryPage).toBe("function");
  });
});
