/** The entries of `entries` that a published package does not export, or whose files are missing. */
export function missingEntries(pkgDir, entries) {
  const pkg = JSON.parse(readFileSync(join(pkgDir, "package.json"), "utf8"));
  return entries.filter((entry) => {
    const target = pkg.exports?.[entry];
    const files = target && typeof target === "object" ? Object.values(target) : [target];
    return !target || files.some((file) => typeof file !== "string" || !existsSync(join(pkgDir, file)));
  });
}

/** Every package any consumer installs, once, in a stable order. */
export const PACKAGES = [...new Set(Object.values(CONSUMERS).flat())];

/** Reads a published registry (`<pkg>/registry/index.json` + one `<name>.json` per item). */
export function readRegistry(pkgDir) {
  const dir = join(pkgDir, "registry");
  const index = JSON.parse(readFileSync(join(dir, "index.json"), "utf8"));
  return index.items.map((entry) => JSON.parse(readFileSync(join(dir, `${entry.name}.json`), "utf8")));
}

/**
 * The examples of one side (`web` or `native`) of a registry, each with the module the package exports for it.
 * An example whose compiled module is missing from the package is returned in `missing` — a consumer cannot import it.
 */
export function examplesOf(pkgDir, side) {
  const found = [];
  const missing = [];
  for (const item of readRegistry(pkgDir)) {
    for (const example of item[side]?.examples ?? []) {
      const compiled = join(pkgDir, "registry", example.path.replace(/\.tsx$/, ".js"));
      const entry = { component: item.name, title: item.title ?? item.name, name: example.name, module: example.module };
      (existsSync(compiled) ? found : missing).push(entry);
    }
  }
  return { found, missing };
}

const ident = (i) => `Example${i}`;
const literal = (value) => JSON.stringify(value);

/**
 * One Next.js page per component: a Server Component importing the component's published examples, as a product
 * would — so `next build` proves each one compiles, type-checks and prerenders ("server by default" included).
 * Returns `{ path, source }` pairs relative to the app root, plus the index page listing them.
 */
export function webPages(pkgName, examples) {
  const byComponent = new Map();
  for (const example of examples) {
    if (!byComponent.has(example.component)) byComponent.set(example.component, []);
    byComponent.get(example.component).push(example);
  }
  const pages = [];
  for (const [component, list] of byComponent) {
    const imports = list.map((e, i) => `import ${ident(i)} from ${literal(e.module)};`).join("\n");
    const sections = list
      .map((e, i) => `      <section data-example=${literal(`${component}/${e.name}`)}>\n        <h2>${escapeJsx(e.name)}</h2>\n        <${ident(i)} />\n      </section>`)
      .join("\n");
    pages.push({
      path: `app/${pkgName}/${component}/page.tsx`,
      source: `// GENERATED by tools/consumer-smoke — the published examples of ${pkgName}/${component}.\n${imports}\n\nexport default function Page() {\n  return (\n    <main>\n      <h1>${escapeJsx(list[0].title)}</h1>\n${sections}\n    </main>\n  );\n}\n`,
    });
  }
  const links = [...byComponent.keys()].map((c) => `        <li><a href=${literal(`/${pkgName}/${c}`)}>${escapeJsx(c)}</a></li>`).join("\n");
  pages.push({
    path: `app/${pkgName}/page.tsx`,
    source: `// GENERATED by tools/consumer-smoke.\nexport default function Page() {\n  return (\n    <main>\n      <ul>\n${links}\n      </ul>\n    </main>\n  );\n}\n`,
  });
  return pages;
}

/**
 * The Expo app's screen: every published React Native example, inside the kit's ThemeProvider and Toaster, in one
 * scroll view — so the type-check and the Metro bundle (`expo export`) prove each one resolves and compiles.
 */
export function nativeApp(examples) {
  const imports = examples.map((e, i) => `import ${ident(i)} from ${literal(e.module)};`).join("\n");
  const rows = examples
    .map((e, i) => `          <View key=${literal(`${e.component}/${e.name}`)} style={{ gap: 8 }}>\n            <Txt variant="caption">${escapeJsx(`${e.component} — ${e.name}`)}</Txt>\n            <${ident(i)} />\n          </View>`)
    .join("\n");
  return `// GENERATED by tools/consumer-smoke — every published React Native example of @krizaka/ui and @krizaka/charts, under @krizaka/query.
import { useFonts } from "expo-font";
import { ScrollView, Text, View } from "react-native";
import { fontAssets } from "@krizaka/fonts/native/assets";
import { fontFamily } from "@krizaka/fonts/native";
import { ThemeProvider, Toaster, Txt } from "@krizaka/ui/native";
import { radius, themes, typeScale } from "@krizaka/tokens/native";
import { ChatIcon } from "@krizaka/icons/native";
import { createQueryClient, KrizakaQueryProvider } from "@krizaka/query";
import { nativeQueryDefaults } from "@krizaka/query/native";
import { createPersister, PERSIST_MAX_AGE } from "@krizaka/query/persist";
${imports}

const { role, fontWeight, ...display } = typeScale.displayLg;
const queryClient = createQueryClient({ gcTime: PERSIST_MAX_AGE, defaultOptions: nativeQueryDefaults });
export const persister = createPersister({ storage: null });

export default function App() {
  const [loaded] = useFonts(fontAssets);
  return (
    <KrizakaQueryProvider client={queryClient}>
    <ThemeProvider defaultMode="dark">
      <ScrollView contentContainerStyle={{ gap: 24, padding: 16, backgroundColor: themes.dark.surface1, borderRadius: radius.lg }}>
        <Text style={{ ...display, color: themes.dark.textPrimary, fontFamily: loaded ? fontFamily(role, Number(fontWeight)) : undefined }}>Krizaka</Text>
        <ChatIcon color={themes.dark.textPrimary} title="Chat" />
${rows}
      </ScrollView>
      <Toaster closeLabel="Close" />
    </ThemeProvider>
    </KrizakaQueryProvider>
  );
}
`;
}

function escapeJsx(text) {
  return String(text).replace(/[{}<>]/g, (c) => `{${literal(c)}}`);
}

/** The result table, in Markdown (the job summary and the console). */
export function summaryMarkdown({ versions, results, date }) {
  const lines = [`## Consumer smoke — ${date}`, "", "| Consumer | Result | Steps |", "| :-- | :-- | :-- |"];
  for (const r of results) {
    const steps = r.steps.map((s) => `${s.ok ? "✅" : "❌"} ${s.name}${s.note ? ` (${s.note})` : ""}`).join("<br>");
    lines.push(`| ${r.consumer} | ${r.ok ? "pass" : "**fail**"} | ${steps} |`);
  }
  lines.push("", "| Package | Version |", "| :-- | :-- |");
  for (const [name, version] of Object.entries(versions)) lines.push(`| \`${name}\` | ${version} |`);
  return `${lines.join("\n")}\n`;
}

/** `--only next,node --dir /tmp/x --keep --expect @krizaka/ui@2.11.0` → options. */
export function parseArgs(argv) {
  const options = { only: Object.keys(CONSUMERS), dir: undefined, keep: false, expect: [] };
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === "--") continue;
    else if (arg === "--only") options.only = argv[++i].split(",").filter(Boolean);
    else if (arg === "--dir") options.dir = argv[++i];
    else if (arg === "--keep") options.keep = true;
    else if (arg === "--expect") options.expect.push(parseSpec(argv[++i]));
    else throw new Error(`consumer-smoke: unknown argument ${arg}`);
  }
  for (const name of options.only) if (!CONSUMERS[name]) throw new Error(`consumer-smoke: unknown consumer ${name}`);
  return options;
}

/** `@krizaka/ui@2.11.0` → `{ name: "@krizaka/ui", version: "2.11.0" }` (a release tag of this repository). */
export function parseSpec(spec) {
  const match = /^(@krizaka\/[a-z0-9-]+)@(\d+\.\d+\.\d+(?:-[\w.]+)?)$/.exec(spec ?? "");
  if (!match) throw new Error(`consumer-smoke: expected @krizaka/<pkg>@x.y.z, got ${spec}`);
  return { name: match[1], version: match[2] };
}
